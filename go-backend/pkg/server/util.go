func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json; charset=utf-8")
	w.Header().Set("Cache-Control", "no-store")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func writeError(w http.ResponseWriter, logger *log.Logger, err error) {
	ae, ok := asAPIError(err)
	if !ok {
		if logger != nil {
			logger.Printf("errore interno: %v", err)
		}
		ae = newErr(http.StatusInternalServerError, "internal", "errore interno del server")
	}
	body := map[string]any{"error": ae.Message, "code": ae.Code}
	if ae.Offset != nil {
		body["offset"] = *ae.Offset
	}
	writeJSON(w, ae.Status, body)
}

func readJSON(w http.ResponseWriter, r *http.Request, v any) error {
	r.Body = http.MaxBytesReader(w, r.Body, 4<<20)
	dec := json.NewDecoder(r.Body)
	if err := dec.Decode(v); err != nil {
		return newErr(http.StatusBadRequest, "bad_json", "JSON non valido")
	}
	return nil
}

func bearerToken(r *http.Request) string {
	h := r.Header.Get("Authorization")
	if len(h) > 7 && strings.EqualFold(h[:7], "bearer ") {
		return strings.TrimSpace(h[7:])
	}
	return ""
}
